import numpy as np
numbers = np.array([1, 2, 3, 4, 5])
print("Original array:", numbers)

print("add 10 to each element:", numbers + 10)
print("multiply each element by 2:", numbers * 2)
print("average of the elements:", np.mean(numbers))
print("maximum value in the array:", np.max(numbers))
print("minimum value in the array:", np.min(numbers))
print("sum of the elements:", np.sum(numbers))
